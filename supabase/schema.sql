-- Longit equipment management: initial secure schema scaffold
-- Run in Supabase SQL Editor. This is a starting schema; frontend integration is still required.

create table if not exists public.equipment (
  id bigint generated by default as identity primary key,
  code text not null unique,
  department text,
  assigned_to text,
  brand text,
  model text,
  serial_number text,
  paper_size text,
  purchase_date date,
  in_use_date date,
  cost numeric(14,2) not null default 0,
  status text not null default 'Đang sử dụng',
  location text,
  evaluation text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.incidents (
  id bigint generated by default as identity primary key,
  incident_code text not null unique,
  incident_date date,
  equipment_code text not null references public.equipment(code) on update cascade on delete restrict,
  issue text not null,
  cause text,
  resolution text,
  completed_date date,
  status text not null default 'Đang xử lý',
  incident_type text,
  handler text,
  cost numeric(14,2) not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.equipment enable row level security;
alter table public.incidents enable row level security;

-- Default safe policy: authenticated users can read; only explicitly approved admins can write.
-- Create public.admin_users and populate it with the admin user's auth.uid() after creating the account.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create or replace function public.is_longit_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a where a.user_id = (select auth.uid())
  );
$$;

-- No anonymous access by default. Signed-in users may read records.
drop policy if exists "signed in can read equipment" on public.equipment;
create policy "signed in can read equipment" on public.equipment
  for select to authenticated using (true);
drop policy if exists "admins can insert equipment" on public.equipment;
create policy "admins can insert equipment" on public.equipment
  for insert to authenticated with check (public.is_longit_admin());
drop policy if exists "admins can update equipment" on public.equipment;
create policy "admins can update equipment" on public.equipment
  for update to authenticated using (public.is_longit_admin()) with check (public.is_longit_admin());
drop policy if exists "admins can delete equipment" on public.equipment;
create policy "admins can delete equipment" on public.equipment
  for delete to authenticated using (public.is_longit_admin());

drop policy if exists "signed in can read incidents" on public.incidents;
create policy "signed in can read incidents" on public.incidents
  for select to authenticated using (true);
drop policy if exists "admins can insert incidents" on public.incidents;
create policy "admins can insert incidents" on public.incidents
  for insert to authenticated with check (public.is_longit_admin());
drop policy if exists "admins can update incidents" on public.incidents;
create policy "admins can update incidents" on public.incidents
  for update to authenticated using (public.is_longit_admin()) with check (public.is_longit_admin());
drop policy if exists "admins can delete incidents" on public.incidents;
create policy "admins can delete incidents" on public.incidents
  for delete to authenticated using (public.is_longit_admin());

